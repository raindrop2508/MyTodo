type Key = keyof typeof dict.en;

interface I18nState {
  lang: Lang;
  setLang: (l: Lang) => void;
}

export const useI18n = create<I18nState>((set) => ({
  lang: "en",
  setLang: (lang) => set({ lang }),
}));

export function useT() {
  const lang = useI18n((s) => s.lang);
  return (k: Key) => dict[lang][k] ?? dict.en[k] ?? k;
}